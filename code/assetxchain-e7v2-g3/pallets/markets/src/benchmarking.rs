fn required_stake<T>() -> BalanceOf<T>
where
    T: Config + pallet_collaterals::Config,
    BalanceOf<T>: From<CollateralBalanceOf<T>>,
{
    <T as pallet_collaterals::Config>::MinMarketOperatorCollateral::get().into()
}

fn fund_operator<T>(operator: &T::AccountId)
where
    T: Config + pallet_collaterals::Config,
{
    let minimum = <T as pallet_collaterals::Config>::MinMarketOperatorCollateral::get();
    let funding = minimum
        .saturating_mul(10u32.into())
        .saturating_add(<T as pallet_collaterals::Config>::Currency::minimum_balance());
    <T as pallet_collaterals::Config>::Currency::make_free_balance_be(operator, funding);
}

fn capacity_tier<T>() -> MarketCapacityTier<BalanceOf<T>>
where
    T: Config + pallet_collaterals::Config,
    BalanceOf<T>: From<CollateralBalanceOf<T>>,
{
    MarketCapacityTier {
        tier_id: 1,
        required_stake: required_stake::<T>(),
        max_active_orders: 100,
        max_funded_orders: 50,
        max_active_exposure_value: 1_000_000u32.into(),
    }
}

fn insert_market<T>(
    operator: T::AccountId,
    contract_address: T::AccountId,
    status: MarketStatus,
) -> MarketId
where
    T: Config + pallet_collaterals::Config,
    BalanceOf<T>: From<CollateralBalanceOf<T>>,
{
    let market_id = [7u8; 32];
    let registration = MarketRegistration {
        market_id,
        operator,
        contract_address: contract_address.clone(),
        code_hash: [9u8; 32],
        protocol_version: T::SettlementProtocolVersion::get(),
        capabilities: MarketCapabilities::transaction_operations(),
        capacity_tier: 1,
        stake: required_stake::<T>(),
        active_orders: 0,
        funded_orders: 0,
        active_exposure_value: 0u32.into(),
        status,
        registered_at: frame_system::Pallet::<T>::block_number(),
        exit_requested_at: None,
    };
    MarketRegistrations::<T>::insert(market_id, registration);
    MarketFeeBps::<T>::insert(market_id, 0);
    ContractMarketIds::<T>::insert(contract_address, market_id);
    market_id
}

fn deploy_market_contract<T>(operator: &T::AccountId) -> T::AccountId
where
    T: Config + pallet_contracts::Config,
{
    let upload = pallet_contracts::Pallet::<T>::bare_upload_code(
        operator.clone(),
        REAL_MARKET_WASM.to_vec(),
        None,
        Determinism::Enforced,
    )
    .expect("benchmark market code uploads");
    let instantiate = pallet_contracts::Pallet::<T>::bare_instantiate(
        operator.clone(),
        0u32.into(),
        Weight::MAX,
        None,
        Code::Existing(upload.code_hash),
        Vec::from([0x9b, 0xae, 0x9d, 0x5e]),
        operator.encode(),
        DebugInfo::Skip,
        CollectEvents::Skip,
    );
    instantiate
        .result
        .expect("benchmark market contract instantiates")
        .account_id
}

#[benchmarks(where
	T: pallet_contracts::Config + pallet_collaterals::Config,
	BalanceOf<T>: From<CollateralBalanceOf<T>>,
)]
mod benchmarks {
    use super::*;

    #[benchmark]
    fn set_capacity_tier() {
        let tier = capacity_tier::<T>();

        #[extrinsic_call]
        _(RawOrigin::Root, tier.clone());

        assert_eq!(CapacityTiers::<T>::get(tier.tier_id), Some(tier));
    }

    #[benchmark]
    fn register_market() {
        let operator: T::AccountId = whitelisted_caller();
        fund_operator::<T>(&operator);
        CapacityTiers::<T>::insert(1, capacity_tier::<T>());
        let contract_address = deploy_market_contract::<T>(&operator);
        let capabilities = MarketCapabilities::transaction_operations();

        #[extrinsic_call]
        _(
            RawOrigin::Signed(operator),
            contract_address.clone(),
            [9u8; 32],
            capabilities,
            1,
            0,
        );

        let market_id = ContractMarketIds::<T>::get(contract_address)
            .expect("registered market has a stable id");
        assert_eq!(
            MarketRegistrations::<T>::get(market_id).map(|market| market.status),
            Some(MarketStatus::Active)
        );
    }

    #[benchmark]
    fn restrict_market() {
        let operator: T::AccountId = account("operator", 0, 0);
        let contract_address: T::AccountId = account("contract", 0, 0);
        let market_id = insert_market::<T>(operator, contract_address, MarketStatus::Active);

        #[extrinsic_call]
        _(RawOrigin::Root, market_id);

        assert_eq!(
            MarketRegistrations::<T>::get(market_id).map(|market| market.status),
            Some(MarketStatus::Restricted)
        );
    }

    #[benchmark]
    fn activate_market() {
        let operator: T::AccountId = account("operator", 0, 0);
        let contract_address: T::AccountId = account("contract", 0, 0);
        let market_id = insert_market::<T>(operator, contract_address, MarketStatus::Restricted);

        #[extrinsic_call]
        _(RawOrigin::Root, market_id);

        assert_eq!(
            MarketRegistrations::<T>::get(market_id).map(|market| market.status),
            Some(MarketStatus::Active)
        );
    }

    #[benchmark]
    fn request_exit() {
        let operator: T::AccountId = account("operator", 0, 0);
        let contract_address: T::AccountId = account("contract", 0, 0);
        let market_id =
            insert_market::<T>(operator.clone(), contract_address, MarketStatus::Active);

        #[extrinsic_call]
        _(RawOrigin::Signed(operator), market_id);

        assert_eq!(
            MarketRegistrations::<T>::get(market_id).map(|market| market.status),
            Some(MarketStatus::Exiting)
        );
    }

    #[benchmark]
    fn deregister_market() {
        let operator: T::AccountId = account("operator", 0, 0);
        let contract_address: T::AccountId = account("contract", 0, 0);
        fund_operator::<T>(&operator);
        T::StakeHandler::pledge(&operator, required_stake::<T>())
            .expect("benchmark operator stake is accepted");
        let market_id = insert_market::<T>(
            operator.clone(),
            contract_address.clone(),
            MarketStatus::Exiting,
        );
        let release_block: BlockNumberFor<T> = (365u32 * 2 * 24 * 60 + 1).into();
        frame_system::Pallet::<T>::set_block_number(release_block);

        #[extrinsic_call]
        _(RawOrigin::Signed(operator), market_id);

        assert_eq!(
            MarketRegistrations::<T>::get(market_id).map(|market| market.status),
            Some(MarketStatus::Deregistered)
        );
        assert!(!ContractMarketIds::<T>::contains_key(contract_address));
    }
}
